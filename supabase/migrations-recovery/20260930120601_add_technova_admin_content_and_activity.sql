create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique,
  excerpt text,
  content text not null default '',
  image_url text,
  category text not null default 'Technology',
  published boolean not null default false,
  author_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.site_content (
  id bigint generated by default as identity primary key,
  content_key text not null unique,
  content_value text not null default '',
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create table if not exists public.admin_activity_log (
  id bigint generated by default as identity primary key,
  admin_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  target_type text,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists is_disabled boolean not null default false;

create index if not exists articles_published_idx on public.articles(published, created_at desc);
create index if not exists articles_category_idx on public.articles(category);
create index if not exists admin_activity_log_created_idx on public.admin_activity_log(created_at desc);
create index if not exists admin_activity_log_action_idx on public.admin_activity_log(action);

alter table public.articles enable row level security;
alter table public.site_content enable row level security;
alter table public.admin_activity_log enable row level security;

-- Public users may read published articles and public site content.
drop policy if exists articles_public_read on public.articles;
create policy articles_public_read on public.articles for select using (published = true or exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin'));

drop policy if exists site_content_public_read on public.site_content;
create policy site_content_public_read on public.site_content for select using (true);

-- Admins can fully manage admin-controlled content and logs.
drop policy if exists articles_admin_all on public.articles;
create policy articles_admin_all on public.articles for all using (exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin')) with check (exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin'));

drop policy if exists site_content_admin_all on public.site_content;
create policy site_content_admin_all on public.site_content for all using (exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin')) with check (exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin'));

drop policy if exists admin_activity_admin_read on public.admin_activity_log;
create policy admin_activity_admin_read on public.admin_activity_log for select using (exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin'));

drop policy if exists admin_activity_admin_insert on public.admin_activity_log;
create policy admin_activity_admin_insert on public.admin_activity_log for insert with check (admin_user_id = auth.uid() and exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin'));

