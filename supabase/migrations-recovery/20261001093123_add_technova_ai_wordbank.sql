create table if not exists public.ai_wordbank (
  id bigint generated by default as identity primary key,
  question text not null,
  normalized_question text not null unique,
  answer text not null,
  times_used bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists ai_wordbank_normalized_question_idx
  on public.ai_wordbank (normalized_question);

alter table public.ai_wordbank enable row level security;

revoke all on table public.ai_wordbank from anon, authenticated;

comment on table public.ai_wordbank is 'Server-side TechNova AI question and answer cache. Accessed by the technova-ai Edge Function using the service role.';
