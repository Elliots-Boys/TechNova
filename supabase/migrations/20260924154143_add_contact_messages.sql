create table if not exists public.contact_messages (
    id bigint generated by default as identity primary key,
    name text not null,
    email text not null,
    subject text not null,
    message text not null,
    created_at timestamptz not null default now()
  );

alter table public.contact_messages enable row level security;

drop policy if exists "contact_messages_public_insert" on public.contact_messages;
create policy "contact_messages_public_insert"
on public.contact_messages
for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 2 and 100
  and char_length(trim(email)) between 5 and 320
  and char_length(trim(subject)) between 2 and 160
  and char_length(trim(message)) between 5 and 5000
);

revoke select, update, delete on public.contact_messages from anon, authenticated;
grant insert on public.contact_messages to anon, authenticated;
