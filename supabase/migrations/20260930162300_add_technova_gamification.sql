create table if not exists public.user_xp (
  user_id uuid primary key references auth.users(id) on delete cascade,
  xp integer not null default 0 check (xp >= 0),
  level integer not null default 1 check (level >= 1),
  updated_at timestamptz not null default now()
);

create table if not exists public.achievements (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text not null default '',
  icon text not null default '🏆',
  xp_reward integer not null default 0 check (xp_reward >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.user_achievements (
  user_id uuid not null references auth.users(id) on delete cascade,
  achievement_id bigint not null references public.achievements(id) on delete cascade,
  earned_at timestamptz not null default now(),
  primary key (user_id, achievement_id)
);

create index if not exists user_xp_xp_idx on public.user_xp (xp desc, updated_at desc);
create index if not exists user_achievements_user_idx on public.user_achievements (user_id, earned_at desc);

alter table public.user_xp enable row level security;
alter table public.achievements enable row level security;
alter table public.user_achievements enable row level security;

