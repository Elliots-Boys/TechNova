create or replace function public.get_leaderboard(limit_count integer default 50)
returns table (
  user_id uuid,
  display_name text,
  avatar_url text,
  xp integer,
  level integer,
  rank bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select
    ux.user_id,
    coalesce(p.display_name, 'Unnamed user') as display_name,
    p.avatar_url,
    ux.xp,
    ux.level,
    row_number() over (order by ux.xp desc, ux.updated_at asc) as rank
  from public.user_xp ux
  left join public.profiles p on p.id = ux.user_id
  where coalesce(p.is_disabled, false) = false
  order by ux.xp desc, ux.updated_at asc
  limit greatest(1, least(limit_count, 200));
$$;

grant execute on function public.get_leaderboard(integer) to authenticated;

create or replace function public.recalculate_user_level(target_user uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  current_xp integer;
  new_level integer;
begin
  if target_user is null then return 1; end if;
  select xp into current_xp from public.user_xp where user_id = target_user;
  if current_xp is null then
    insert into public.user_xp(user_id,xp,level) values(target_user,0,1)
    on conflict (user_id) do nothing;
    current_xp := 0;
  end if;
  new_level := greatest(1, floor(current_xp / 100.0)::integer + 1);
  update public.user_xp set level = new_level, updated_at = now() where user_id = target_user;
  return new_level;
end;
$$;

grant execute on function public.recalculate_user_level(uuid) to authenticated;

