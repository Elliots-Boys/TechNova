-- Fix TechNova achievements/leaderboard access and add the missing ticket system.

-- 1) Leaderboard RPC: only signed-in users should be able to call it.
revoke execute on function public.get_leaderboard(integer) from anon;
grant execute on function public.get_leaderboard(integer) to authenticated;

-- 2) Make achievement/leaderboard data explicitly readable by signed-in users.
drop policy if exists "Users can view achievements" on public.achievements;
create policy "Users can view achievements"
on public.achievements
for select
to authenticated
using (true);

drop policy if exists "Users can view earned achievements" on public.user_achievements;
create policy "Users can view earned achievements"
on public.user_achievements
for select
to authenticated
using (true);

drop policy if exists "Users can view xp leaderboard" on public.user_xp;
create policy "Users can view xp leaderboard"
on public.user_xp
for select
to authenticated
using (true);

-- 3) Missing ticket system.
create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject text not null check (length(trim(subject)) between 1 and 200),
  message text not null check (length(trim(message)) between 1 and 10000),
  status text not null default 'open' check (status in ('open','in_progress','resolved','closed')),
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  admin_response text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists tickets_user_id_idx on public.tickets(user_id);
create index if not exists tickets_status_idx on public.tickets(status);
create index if not exists tickets_created_at_idx on public.tickets(created_at desc);

alter table public.tickets enable row level security;

-- Users can create and view their own tickets.
drop policy if exists "Users can create own tickets" on public.tickets;
create policy "Users can create own tickets"
on public.tickets
for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can view own tickets" on public.tickets;
create policy "Users can view own tickets"
on public.tickets
for select
to authenticated
using (auth.uid() = user_id);

-- Users may update their own ticket while it is still open/in progress.
drop policy if exists "Users can update own open tickets" on public.tickets;
create policy "Users can update own open tickets"
on public.tickets
for update
to authenticated
using (auth.uid() = user_id and status in ('open','in_progress'))
with check (auth.uid() = user_id and status in ('open','in_progress'));

-- Admins can manage all tickets.
drop policy if exists "Admins can view all tickets" on public.tickets;
create policy "Admins can view all tickets"
on public.tickets
for select
to authenticated
using ((select private.is_admin()));

drop policy if exists "Admins can update all tickets" on public.tickets;
create policy "Admins can update all tickets"
on public.tickets
for update
to authenticated
using ((select private.is_admin()))
with check ((select private.is_admin()));

drop policy if exists "Admins can delete tickets" on public.tickets;
create policy "Admins can delete tickets"
on public.tickets
for delete
to authenticated
using ((select private.is_admin()));

-- Keep updated_at current.
create or replace function public.set_ticket_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at := now();
  if new.status in ('resolved','closed') and old.status not in ('resolved','closed') then
    new.resolved_at := now();
  elsif new.status not in ('resolved','closed') then
    new.resolved_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists tickets_set_updated_at on public.tickets;
create trigger tickets_set_updated_at
before update on public.tickets
for each row execute function public.set_ticket_updated_at();

-- 4) Ensure the leaderboard RPC is usable by authenticated clients and never exposes disabled profiles.
-- (The function already filters disabled profiles; this grant/revoke makes its intended audience explicit.)

-- 5) Ensure existing users have an XP row. This is idempotent and helps the leaderboard render immediately.
insert into public.user_xp (user_id, xp, level)
select p.id, 0, 1
from public.profiles p
where coalesce(p.is_disabled, false) = false
on conflict (user_id) do nothing;
